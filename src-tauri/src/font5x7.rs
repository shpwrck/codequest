#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_row_fits_five_pixels() {
        for character in ' '..='~' {
            assert!(glyph(character).iter().all(|row| row & !0b11111 == 0));
        }
    }

    #[test]
    fn every_printable_ascii_character_has_a_glyph() {
        for character in ' '..='~' {
            let character = character.to_ascii_uppercase();
            if character != '?' {
                assert_ne!(glyph(character), UNKNOWN, "missing glyph for {character:?}");
            }
        }
    }

    #[test]
    fn ambiguous_gameplay_glyphs_are_distinct() {
        for (left, right) in [('0', 'O'), ('1', 'I'), ('5', 'S'), ('M', 'N'), ('R', 'P')] {
            assert_ne!(glyph(left), glyph(right), "{left} and {right} must differ");
        }
    }

    #[test]
    fn compact_cell_has_one_pixel_spacing() {
        assert_eq!(GLYPH_ADVANCE, GLYPH_WIDTH + 1);
        assert_eq!(LINE_HEIGHT, GLYPH_HEIGHT + 1);
    }
}
